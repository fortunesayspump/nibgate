const Joi = require('joi');

const createPost = {
  body: Joi.object().keys({
    title: Joi.string().required().min(4).max(200),
    slug: Joi.string().optional().max(100),
    bodyMarkdown: Joi.string().optional().min(20).allow(''),
    excerpt: Joi.string().optional().max(300).allow(''),
    tag: Joi.string().optional().max(40).allow(''),
    tags: Joi.alternatives().try(Joi.string(), Joi.array().items(Joi.string())).optional().allow(''),
    coverUrl: Joi.string().uri().optional().allow(''),
    videoUrl: Joi.string().uri().optional().allow(''),
    audioUrl: Joi.string().optional().allow(''),
    audioStorageRef: Joi.string().optional().allow(''),
    audioEncryptedKey: Joi.string().optional().allow(''),
    audioContentType: Joi.string().optional().allow(''),
    documentUrl: Joi.string().optional().allow(''),
    documentName: Joi.string().optional().allow(''),
    documentSize: Joi.number().optional().allow(null),
    documentStorageRef: Joi.string().optional().allow(''),
    documentEncryptedKey: Joi.string().optional().allow(''),
    documentContentType: Joi.string().optional().allow(''),
    media: Joi.string().optional().allow(''),
    coverKey: Joi.string().optional().allow(''),
    type: Joi.string().valid('article', 'photo', 'music', 'video', 'document').optional(),
    status: Joi.string().valid('draft', 'published').optional(),
    featured: Joi.boolean().optional(),
    price: Joi.string().optional().allow('', null),
    whitelist: Joi.array().items(Joi.string().pattern(/^0x[a-fA-F0-9]{40}$/)).optional(),
    whitelistPrice: Joi.alternatives().try(Joi.string().allow(''), Joi.number().min(0), Joi.allow(null)).optional(),
    publicAccess: Joi.boolean().optional(),
  }).unknown(true),
};

